// Downloads the Google Fonts used by src/game.html (latin and latin-ext only) into fonts/,
// so the web app makes no requests to Google. Run once after changing the font link; commit the result.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const SUBSETS = ['latin-ext', 'latin'];
const LICENSES = {
  'Bagel Fat One': 'https://raw.githubusercontent.com/google/fonts/main/ofl/bagelfatone/OFL.txt',
  'Bricolage Grotesque': 'https://raw.githubusercontent.com/google/fonts/main/ofl/bricolagegrotesque/OFL.txt'
};

const get = async (url, as) => {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return as === 'buf' ? Buffer.from(await res.arrayBuffer()) : res.text();
};

const game = readFileSync(new URL('src/game.html', root), 'utf8');
const cssUrl = game.match(/href="(https:\/\/fonts\.googleapis\.com\/css2\?[^"]+)"/)[1].replace(/&amp;/g, '&');
const css = await get(cssUrl);
const dir = new URL('fonts/', root); mkdirSync(dir, { recursive: true });

const files = new Map(), out = ['/* Generated by scripts/fetch-fonts.mjs from Google Fonts (SIL Open Font License, see OFL-*.txt). */'];
for (const [, subset, body] of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
  if (!SUBSETS.includes(subset)) continue;
  const family = body.match(/font-family: '([^']+)'/)[1], src = body.match(/url\(([^)]+)\)/)[1];
  if (!files.has(src)) files.set(src, `${family.toLowerCase().replace(/ /g, '-')}-${subset}.woff2`);
  out.push(`@font-face {${body.replace(src, files.get(src))}}`);
}
for (const [src, name] of files) writeFileSync(new URL(name, dir), await get(src, 'buf'));
for (const [family, url] of Object.entries(LICENSES)) writeFileSync(new URL(`OFL-${family.replace(/ /g, '')}.txt`, dir), await get(url));
writeFileSync(new URL('fonts.css', dir), out.join('\n') + '\n');
console.log(`fonts/: ${files.size} woff2, fonts.css, ${Object.keys(LICENSES).length} licenses`);
